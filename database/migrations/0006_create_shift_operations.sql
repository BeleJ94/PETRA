-- Opérations d'un poste : remises d'argent, sorties hors vente, ventes à crédit, dépenses de caisse.
-- Chacune est rattachée à une tranche, donc à un prix et à un taux.

-- Argent remis par le pompiste. L'USD est converti en CDF au taux de la tranche (amount_cdf figé).
CREATE TABLE cash_handovers (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    station_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    shift_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    segment_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    amount BIGINT NOT NULL,
    currency CHAR(3) NOT NULL,
    exchange_rate_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    amount_cdf BIGINT NOT NULL,
    received_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    handed_at DATETIME NOT NULL,
    note VARCHAR(255) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    -- Correction : nouvelle ligne liée à l'originale, motivée et approuvée par un second utilisateur.
    corrects_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    correction_reason VARCHAR(255) NULL,
    approved_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    approved_at DATETIME NULL,
    PRIMARY KEY (id),
    KEY idx_ch_station_handed (station_id, handed_at),
    KEY idx_ch_shift (shift_id),
    CONSTRAINT fk_ch_station FOREIGN KEY (station_id) REFERENCES stations (id),
    CONSTRAINT fk_ch_shift FOREIGN KEY (shift_id) REFERENCES shifts (id),
    CONSTRAINT fk_ch_segment FOREIGN KEY (segment_id) REFERENCES shift_segments (id),
    CONSTRAINT fk_ch_exchange_rate FOREIGN KEY (exchange_rate_id) REFERENCES exchange_rates (id),
    CONSTRAINT fk_ch_received_by FOREIGN KEY (received_by) REFERENCES users (id),
    CONSTRAINT chk_ch_amount CHECK (amount >= 0 AND amount_cdf >= 0),
    CONSTRAINT chk_ch_currency CHECK (currency IN ('CDF', 'USD')),
    CONSTRAINT chk_ch_rate CHECK ((currency = 'CDF' AND amount_cdf = amount) OR (currency = 'USD' AND exchange_rate_id IS NOT NULL)),
    CONSTRAINT fk_ch_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_ch_corrects FOREIGN KEY (corrects_id) REFERENCES cash_handovers (id),
    CONSTRAINT fk_ch_approved_by FOREIGN KEY (approved_by) REFERENCES users (id),
    CONSTRAINT chk_ch_correction CHECK (corrects_id IS NULL OR (approved_by IS NOT NULL AND approved_at IS NOT NULL AND correction_reason IS NOT NULL)),
    CONSTRAINT chk_ch_four_eyes CHECK (approved_by IS NULL OR approved_by <> created_by)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Volume passé au compteur sans être vendu : il diminue l'attendu du poste.
-- tank_return : carburant d'essai reversé en cuve (il revient au stock).
CREATE TABLE non_sale_outputs (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    station_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    shift_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    segment_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    nozzle_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    output_type ENUM('test', 'calibration', 'internal_use', 'tank_return') NOT NULL,
    volume_l DECIMAL(12,2) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    occurred_at DATETIME NOT NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    -- Correction : nouvelle ligne liée à l'originale, motivée et approuvée par un second utilisateur.
    corrects_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    correction_reason VARCHAR(255) NULL,
    approved_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    approved_at DATETIME NULL,
    PRIMARY KEY (id),
    KEY idx_nso_station_occurred (station_id, occurred_at),
    KEY idx_nso_shift (shift_id),
    CONSTRAINT fk_nso_station FOREIGN KEY (station_id) REFERENCES stations (id),
    CONSTRAINT fk_nso_shift FOREIGN KEY (shift_id) REFERENCES shifts (id),
    CONSTRAINT fk_nso_segment FOREIGN KEY (segment_id) REFERENCES shift_segments (id),
    CONSTRAINT fk_nso_nozzle FOREIGN KEY (nozzle_id) REFERENCES nozzles (id),
    CONSTRAINT chk_nso_volume CHECK (volume_l > 0),
    CONSTRAINT fk_nso_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_nso_corrects FOREIGN KEY (corrects_id) REFERENCES non_sale_outputs (id),
    CONSTRAINT fk_nso_approved_by FOREIGN KEY (approved_by) REFERENCES users (id),
    CONSTRAINT chk_nso_correction CHECK (corrects_id IS NULL OR (approved_by IS NOT NULL AND approved_at IS NOT NULL AND correction_reason IS NOT NULL)),
    CONSTRAINT chk_nso_four_eyes CHECK (approved_by IS NULL OR approved_by <> created_by)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Vente servie sans encaissement immédiat (bon client) : elle diminue l'argent attendu du poste.
CREATE TABLE credit_sales (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    station_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    shift_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    segment_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    nozzle_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    customer_name VARCHAR(120) NOT NULL,
    voucher_no VARCHAR(60) NULL,
    volume_l DECIMAL(12,2) NOT NULL,
    price_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    amount BIGINT NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'CDF',
    sold_at DATETIME NOT NULL,
    note VARCHAR(255) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    -- Correction : nouvelle ligne liée à l'originale, motivée et approuvée par un second utilisateur.
    corrects_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    correction_reason VARCHAR(255) NULL,
    approved_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    approved_at DATETIME NULL,
    PRIMARY KEY (id),
    KEY idx_cs_station_sold (station_id, sold_at),
    KEY idx_cs_shift (shift_id),
    KEY idx_cs_customer (station_id, customer_name),
    CONSTRAINT fk_cs_station FOREIGN KEY (station_id) REFERENCES stations (id),
    CONSTRAINT fk_cs_shift FOREIGN KEY (shift_id) REFERENCES shifts (id),
    CONSTRAINT fk_cs_segment FOREIGN KEY (segment_id) REFERENCES shift_segments (id),
    CONSTRAINT fk_cs_nozzle FOREIGN KEY (nozzle_id) REFERENCES nozzles (id),
    CONSTRAINT fk_cs_price FOREIGN KEY (price_id) REFERENCES prices (id),
    CONSTRAINT chk_cs_values CHECK (volume_l > 0 AND amount >= 0),
    CONSTRAINT chk_cs_currency CHECK (currency IN ('CDF', 'USD')),
    CONSTRAINT fk_cs_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_cs_corrects FOREIGN KEY (corrects_id) REFERENCES credit_sales (id),
    CONSTRAINT fk_cs_approved_by FOREIGN KEY (approved_by) REFERENCES users (id),
    CONSTRAINT chk_cs_correction CHECK (corrects_id IS NULL OR (approved_by IS NOT NULL AND approved_at IS NOT NULL AND correction_reason IS NOT NULL)),
    CONSTRAINT chk_cs_four_eyes CHECK (approved_by IS NULL OR approved_by <> created_by)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

-- Dépense payée avec l'argent de la caisse. Rattachée à un poste quand elle sort de la recette d'un pompiste.
CREATE TABLE cash_expenses (
    id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    station_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    shift_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    segment_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    category VARCHAR(60) NOT NULL,
    description VARCHAR(255) NOT NULL,
    amount BIGINT NOT NULL,
    currency CHAR(3) NOT NULL,
    exchange_rate_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    amount_cdf BIGINT NOT NULL,
    spent_at DATETIME NOT NULL,
    receipt_path VARCHAR(255) NULL,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
    -- Correction : nouvelle ligne liée à l'originale, motivée et approuvée par un second utilisateur.
    corrects_id CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    correction_reason VARCHAR(255) NULL,
    approved_by CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NULL,
    approved_at DATETIME NULL,
    PRIMARY KEY (id),
    KEY idx_ce_station_spent (station_id, spent_at),
    KEY idx_ce_shift (shift_id),
    CONSTRAINT fk_ce_station FOREIGN KEY (station_id) REFERENCES stations (id),
    CONSTRAINT fk_ce_shift FOREIGN KEY (shift_id) REFERENCES shifts (id),
    CONSTRAINT fk_ce_segment FOREIGN KEY (segment_id) REFERENCES shift_segments (id),
    CONSTRAINT fk_ce_exchange_rate FOREIGN KEY (exchange_rate_id) REFERENCES exchange_rates (id),
    CONSTRAINT chk_ce_amount CHECK (amount > 0 AND amount_cdf > 0),
    CONSTRAINT chk_ce_currency CHECK (currency IN ('CDF', 'USD')),
    CONSTRAINT chk_ce_rate CHECK ((currency = 'CDF' AND amount_cdf = amount) OR (currency = 'USD' AND exchange_rate_id IS NOT NULL)),
    CONSTRAINT chk_ce_segment CHECK ((shift_id IS NULL AND segment_id IS NULL) OR (shift_id IS NOT NULL AND segment_id IS NOT NULL)),
    CONSTRAINT fk_ce_created_by FOREIGN KEY (created_by) REFERENCES users (id),
    CONSTRAINT fk_ce_corrects FOREIGN KEY (corrects_id) REFERENCES cash_expenses (id),
    CONSTRAINT fk_ce_approved_by FOREIGN KEY (approved_by) REFERENCES users (id),
    CONSTRAINT chk_ce_correction CHECK (corrects_id IS NULL OR (approved_by IS NOT NULL AND approved_at IS NOT NULL AND correction_reason IS NOT NULL)),
    CONSTRAINT chk_ce_four_eyes CHECK (approved_by IS NULL OR approved_by <> created_by)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
